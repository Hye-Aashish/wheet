export function getBlogBySlug(slug) {
  if (!slug) return blogData[0];
  const found = blogData.find((b) => b.slug === slug);
  return found || blogData[0];
}

export function getRelatedBlogs(currentSlug, limit = 3) {
  return blogData.filter((b) => b.slug !== currentSlug).slice(0, limit);
}
